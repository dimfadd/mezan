// Bahasa untuk sisi pelanggan (menu QR & status pesanan). Layar kasir/admin tetap bahasa Indonesia.
export type Lang = "id" | "en";

export function pickLang(raw: unknown): Lang {
  return raw === "en" ? "en" : "id";
}

/** Pilih teks sesuai bahasa, jatuh ke versi Indonesia kalau versi Inggris kosong. */
export function loc(lang: Lang, id: string, en?: string | null) {
  return lang === "en" && en && en.trim() ? en : id;
}

